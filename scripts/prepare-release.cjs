// Generate release metadata from the actual built Windows installer.
// No credentials, upload, or installation occurs in this script.
const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')
const zlib = require('node:zlib')
const root = path.resolve(__dirname, '..')
const { version } = require('../package.json')
if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error('Only stable semantic versions can be prepared.')
const repository = 'https://github.com/Destroyer236/Mix-Music'
const tag = `v${version}`
const name = `MixMusic-v${version}-x64-Setup.exe`
const file = path.join(root, 'build', name)
const installer = fs.readFileSync(file)
if (installer.length < 5_000_000 || installer.subarray(0, 2).toString() !== 'MZ') throw new Error('A valid built Windows installer is required.')
const sha256 = crypto.createHash('sha256').update(installer).digest('hex')

// 增量更新依赖与安装包配套的 .blockmap。electron-builder 在构建时已生成，
// 这里校验它的完整性（能被解压、块尺寸总和等于安装包长度），再作为资产发布。
const blockmapFile = `${file}.blockmap`
if (!fs.existsSync(blockmapFile)) throw new Error(`A block map generated by electron-builder is required for differential updates: ${path.basename(blockmapFile)}`)
const blockmapRaw = fs.readFileSync(blockmapFile)
let blockmapSize = 0
try {
  const map = JSON.parse(zlib.gunzipSync(blockmapRaw).toString('utf8'))
  const entry = Array.isArray(map.files) ? map.files[0] : null
  if (!entry || !Array.isArray(entry.sizes)) throw new Error('block map has no file entry')
  blockmapSize = entry.offset + entry.sizes.reduce((sum, size) => sum + size, 0)
} catch (error) {
  throw new Error(`The generated block map could not be read: ${error.message}`)
}
if (blockmapSize !== installer.length) throw new Error(`Block map covers ${blockmapSize} bytes but the installer is ${installer.length} bytes.`)

const body = fs.readFileSync(path.join(root, 'docs', 'releases', `${tag}.md`), 'utf8')
const manifestPath = path.join(root, 'updates', 'stable-linkline.json')
const existing = fs.existsSync(manifestPath) ? JSON.parse(fs.readFileSync(manifestPath, 'utf8')).releases : []
if (!Array.isArray(existing)) throw new Error('Existing update manifest is invalid.')
const blockmapName = `${name}.blockmap`
const release = {
  version, name: `Mix Music ${version}`, body,
  publishedAt: new Date().toISOString(),
  pageUrl: `${repository}/releases/tag/${tag}`,
  assets: [
    { name, url: `${repository}/releases/download/${tag}/${name}`, size: installer.length, sha256 },
    { name: blockmapName, url: `${repository}/releases/download/${tag}/${blockmapName}`, size: blockmapRaw.length },
  ],
}
fs.mkdirSync(path.dirname(manifestPath), { recursive: true })
const manifest = { schemaVersion: 1, repository, releases: [release, ...existing.filter(item => item.version !== version)].slice(0, 20) }
fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n')
// Released 1.0.0 / 1.0.1 clients validate the original repository identity.
// GitHub redirects these links to LinkLine; keep their update feed compatible.
fs.writeFileSync(path.join(root, 'updates', 'stable.json'), JSON.stringify(manifest, null, 2).replaceAll(repository, 'https://github.com/yaonikaixin999999/LXMusicRemake') + '\n')
fs.writeFileSync(path.join(root, 'build', 'SHA256SUMS.txt'), `${sha256}  ${name}\n`)
console.log(JSON.stringify({ version, installer: name, size: installer.length, sha256, blockmap: blockmapName, blockmapSize: blockmapRaw.length, manifest: 'updates/stable-linkline.json', compatibilityManifest: 'updates/stable.json' }, null, 2))
